async (page) => {
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:8789/');
  await page.setViewportSize({width:1440,height:1050});
  await page.locator('#modelLabel').filter({hasText:'SD2.5-按次-720P'}).waitFor();
  await page.locator('[data-menu="type"]').click();
  await page.getByText('图片生成',{exact:true}).click();
  await page.locator('#prompt').fill('离线验证：提交后重开页面，任务持续保存');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  await page.locator('#taskFeed .task-card').waitFor();
  const pending=await page.locator('#taskFeed').innerText();
  if(/任务 ID：|上游/.test(pending))throw new Error('Internal task metadata leaked into normal UI');
  await page.locator('#taskFeed .task-card').evaluate(card=>{card.dataset.stableNode='preserved';});
  const progressRefresh=page.waitForResponse(response=>response.url().endsWith('/api/tasks'));
  await page.evaluate(()=>window.dispatchEvent(new Event('online')));
  await progressRefresh;
  if(await page.locator('#taskFeed .task-card').getAttribute('data-stable-node')!=='preserved')throw new Error('Polling replaced the task card node and retriggered its animation');
  // Simulate loss of all browser-local history, then reopen while still running.
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
  await page.locator('#taskFeed .task-card').waitFor();
  await page.getByRole('button',{name:'历史',exact:true}).click();
  await page.locator('#historyList .task-card').waitFor();
  await page.locator('#historyList a').filter({hasText:'下载'}).waitFor();
  const card=page.locator('#historyList .task-card-visual').first();
  const cardBox=await card.boundingBox();
  if(!cardBox||Math.abs(cardBox.height-472)>1)throw new Error('Visual task card lost its fixed desktop height');
  const image=page.locator('#historyList .task-result img').first();
  const src=await image.getAttribute('src');
  if(!src.startsWith('/api/tasks/'))throw new Error('Preview did not use local file');
  await image.evaluate(el=>{if(!el.complete||!el.naturalWidth)throw new Error('Local preview not loaded');if(getComputedStyle(el).objectFit!=='contain')throw new Error('Result preview may crop generated media');el.dataset.playbackSentinel='preserved';});
  const refreshed = page.waitForResponse(response=>response.url().endsWith('/api/tasks'));
  await page.evaluate(()=>window.dispatchEvent(new Event('online')));
  await refreshed;
  if(await page.locator('#taskPersistenceNote').isVisible())throw new Error('Routine persistence note should be hidden');
  if(await image.getAttribute('data-playback-sentinel')!=='preserved')throw new Error('Stable completed preview was recreated');
  await card.getByRole('button',{name:'放大预览'}).click();
  await page.getByRole('dialog',{name:'作品预览'}).waitFor();
  await page.getByRole('button',{name:'关闭预览'}).click();
  await page.screenshot({path:'output/playwright/persistent-task-history.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Task cards cause mobile horizontal overflow');
  if((await card.boundingBox()).width>310)throw new Error('Task card did not adapt to the mobile content column');
  await page.screenshot({path:'output/playwright/task-history-mobile.png',fullPage:true});
  const list=await (await page.request.get('http://127.0.0.1:8789/api/tasks')).json();
  if(!list.tasks[0].result.local_path||!list.tasks[0].id.startsWith('offline-'))throw new Error('No durable local path or task ID');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('PASS: real local journal + offline upstream fixture; submitting, reload without localStorage, resumed history, saved preview. No paid API calls.');
}
