async (page) => {
  await page.goto('http://127.0.0.1:11149/account-lite/index.html');
  await page.getByText('¥128.50', { exact: true }).waitFor();
  await page.getByRole('button', { name: '充值', exact: true }).click();
  await page.route('**/api/user/pay', async (route) => { await route.fetch(); await route.abort('failed'); });
  await page.getByRole('button', { name: '确认并前往支付', exact: true }).click();
  await page.getByRole('button', { name: '确认并支付', exact: true }).click();
  await page.getByText(/网络请求未完成/).waitFor();
  await page.unroute('**/api/user/pay');
  await page.reload();
  await page.getByRole('button', { name: '充值', exact: true }).click();
  await page.getByText('¥50.00', { exact: true }).waitFor();
  if (!await page.getByRole('button', { name: '确认并前往支付', exact: true }).isDisabled()) throw new Error('reload unlocked uncertain payment');
  await page.getByRole('button', { name: '刷新余额与订单', exact: true }).click();
  await page.getByText(/本页尚未找到原订单/).waitFor();
  if (!await page.getByRole('button', { name: '确认并前往支付', exact: true }).isDisabled()) throw new Error('unknown order unlocked');
  await page.getByRole('button', { name: 'API Key', exact: true }).click();
  await page.getByRole('button', { name: '开通 API Key', exact: true }).click();
  await page.getByRole('textbox', { name: '名称', exact: true }).fill('中断恢复测试');
  await page.route('**/api/token/', async (route) => { if (route.request().method() !== 'POST') return route.continue(); await route.fetch(); await route.abort('failed'); });
  await page.getByRole('button', { name: '确认开通', exact: true }).click();
  await page.locator('#key-error').getByText(/网络请求未完成/).waitFor();
  const persisted = await page.evaluate(() => Object.entries(localStorage).filter(([key]) => key.startsWith('hamster-account-lite:pending-')).map(([key, value]) => ({ key, data: JSON.parse(value) })));
  if (JSON.stringify(persisted).includes('access_token') || JSON.stringify(persisted).includes('sk-fixture')) throw new Error('secret persisted');
  await page.unroute('**/api/token/');
  await page.reload();
  await page.getByRole('button', { name: 'API Key', exact: true }).click();
  await page.getByText(/已找到上次开通的 Key/).waitFor();
  if (await page.getByRole('button', { name: '开通 API Key', exact: true }).isDisabled()) throw new Error('original key was not recovered');
  let finishReveal;
  const startedReveal = new Promise((resolve) => { finishReveal = resolve; });
  let releaseReveal;
  const revealGate = new Promise((resolve) => { releaseReveal = resolve; });
  await page.route('**/api/token/7/key', async (route) => { finishReveal(); await revealGate; await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ success: true, data: { key: 'sk-fixture-late-secret' } }) }); });
  await page.getByRole('button', { name: '查看 Key', exact: true }).first().click();
  await startedReveal;
  await page.getByRole('button', { name: '账户余额', exact: true }).click();
  releaseReveal();
  await page.getByRole('button', { name: 'API Key', exact: true }).click();
  if (await page.getByRole('textbox', { name: /的完整 Key/ }).count()) throw new Error('late secret was rendered');
  await page.setViewportSize({ width: 1030, height: 450 });
  await page.getByRole('button', { name: '账户余额', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/account-lite-embedded-450.png' });
  const summary = await page.evaluate(() => ({ viewport: innerHeight, balance: document.getElementById('balance-value').getBoundingClientRect().bottom, header: document.querySelector('.topbar').getBoundingClientRect().height }));
  const server = await (await page.request.get('http://127.0.0.1:11149/__qa/state')).json();
  return { uncertainPaySurvivesReload: true, missingOrderRemainsLocked: true, keyRecoveredWithoutReplay: true, lateSecretDiscarded: true, persistedMetadata: persisted, syntheticPayCalls: server.data.calls.filter((entry) => entry.path === '/api/user/pay').length, syntheticKeyCreateCalls: server.data.calls.filter((entry) => entry.path === '/api/token/' && entry.method === 'POST').length, compactLayout: summary };
}
